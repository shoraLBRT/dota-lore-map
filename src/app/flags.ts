/**
 * Флаг `?nav=new` (#230, SPEC §5.1 «Правила окон»): прототип новой навигации — путь вверху карты, × у каждого окна,
 * без «Свернуть» и чипа героя, клик по пустой карте ничего не закрывает, шторки тянутся пальцем.
 * Флаг — в поиске адреса до hash (`/dota-lore-map/?nav=new#/world`): переходы приложения меняют только hash,
 * поэтому он держится всю сессию. Без флага — прежняя навигация. После приёмки владельцем флаг снимается.
 */
export function navNew(): boolean {
  try {
    return new URLSearchParams(window.location.search).get('nav') === 'new';
  } catch {
    return false;
  }
}
